window.dayInfo = function (day) {
  if (day > 360) {
    return { day, subject: null, unit: '年度挑战', title: FINALE[day - 361], unitIndex: 12, lessonIndex: day - 361 };
  }
  const subject = ORDER[(day - 1) % 6];
  const n = Math.floor((day - 1) / 6);
  const unitIndex = Math.floor(n / 5);
  const lessonIndex = n % 5;
  const [unit, titles] = UNITS[subject][unitIndex];
  return { day, subject, unit, title: titles[lessonIndex], unitIndex, lessonIndex };
};

window.stageOf = function (day) {
  return STAGES.find(s => day >= s.from && day <= s.to);
};
